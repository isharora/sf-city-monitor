"""Person-level resolution:
  (1) contractor principals listed on SFEC 126f4 forms  <->  individual campaign donors
  (2) registered lobbyists                               <->  individual campaign donors
Candidates are generated by (last name, canonical first name) equality; evidence = employer vs contractor/firm similarity,
occupation, location, name rarity. Clear cases are decided by rule; ambiguous ones by Claude (Sonnet; Opus for hard ones).

Outputs data/er/person_matches.parquet: one row per (person_role_id, donor_profile_id) with decision, confidence, rationale.
Donor profiles are (name key, zip5) groups of individual contribution records.
"""
import os, re, json, sys, concurrent.futures as cf
import numpy as np
import pandas as pd
from rapidfuzz import fuzz
from names import canon_first, basic, org_key
import llm

HERE = os.path.dirname(os.path.abspath(__file__))
INT = os.path.join(HERE, '..', 'data', 'interim')
ER = os.path.join(HERE, '..', 'data', 'er')


def lastkey(l):
    l = basic(l)
    l = re.sub(r'\b(JR|SR|II|III|IV|MD|PHD|ESQ|DDS|CPA)\b', '', l)
    return re.sub(r'\s+', ' ', l).strip()


def donor_profiles():
    c = pd.read_parquet(os.path.join(INT, 'contributions.parquet'),
                        columns=['element_nid', 'is_individual', 'donor_first', 'donor_last', 'zip5', 'city', 'state', 'employer',
                                 'occupation', 'amount', 'date', 'recip_kind', 'recip_office', 'filer_name'])
    c = c[c.is_individual].copy()
    c['nk'] = c.donor_last.map(lastkey) + '|' + c.donor_first.map(canon_first)
    c['pid'] = c.nk + '|' + c.zip5.fillna('')
    top = lambda s: ' | '.join([x for x in s.fillna('').astype(str).value_counts().index if x][:3])
    prof = c.groupby('pid').agg(nk=('nk', 'first'), first=('donor_first', top), last=('donor_last', 'first'), zip5=('zip5', 'first'),
                                city=('city', top), state=('state', 'first'), employers=('employer', top), occupations=('occupation', top),
                                n=('amount', 'size'), total=('amount', 'sum'), first_date=('date', 'min'), last_date=('date', 'max'),
                                recipients=('filer_name', top)).reset_index()
    return c[['element_nid', 'pid', 'nk']], prof


EXEC = re.compile(r'\b(CEO|PRESIDENT|FOUNDER|OWNER|PRINCIPAL|PARTNER|CHAIR|DIRECTOR|OFFICER|CFO|COO|EXECUTIVE|VP|VICE PRESIDENT|MANAGING|TRUSTEE|BOARD)\b')


def emp_sim(employers, target_key):
    best = 0
    for e in str(employers).split(' | '):
        k = org_key(e)
        if not k or not target_key:
            continue
        s = min(fuzz.token_set_ratio(k, target_key), 100)
        if len(k) < 4:
            s = min(s, fuzz.ratio(k, target_key))
        best = max(best, s)
    return best


SYSTEM = """You resolve people across San Francisco public records. Decide whether an individual campaign donor profile is the same person as a named person from another record (a principal officer/board member of a city contractor, or a registered lobbyist).
Use: name exactness (middle names/initials, suffixes), employer and occupation vs the organization, location, and name commonness (count of distinct donor profiles sharing the name). Board members of nonprofits usually list their own day-job employer, so a different employer is weak evidence against for board members, but stronger evidence against for CEOs/CFOs/COOs of companies. A common name with no corroboration should be "unsure" or "different".
Answer "same", "different" or "unsure", a confidence (probability your answer is right, 0-1) and a rationale under 30 words."""

SCHEMA = {'type': 'object', 'properties': {'judgments': {'type': 'array', 'items': {'type': 'object', 'properties': {
    'cand_id': {'type': 'integer'}, 'decision': {'type': 'string', 'enum': ['same', 'different', 'unsure']},
    'confidence': {'type': 'number'}, 'rationale': {'type': 'string'}},
    'required': ['cand_id', 'decision', 'confidence', 'rationale'], 'additionalProperties': False}}},
    'required': ['judgments'], 'additionalProperties': False}


def judge(batch, model=llm.SONNET, effort='medium', task='person_match'):
    lines = []
    for r in batch:
        lines.append(f"Candidate {r['cand_id']}:\n  PERSON: {r['person_desc']}\n  DONOR PROFILE: {r['donor_desc']}\n  distinct donor profiles with this name: {r['name_profiles']}")
    prompt = 'Judge each candidate match.\n\n' + '\n'.join(lines)
    return llm.call_json(task, prompt, SCHEMA, system=SYSTEM, model=model, effort=effort)['judgments']


def principals():
    p = pd.read_parquet(os.path.join(INT, 'f126_parties.parquet'))
    p = p[p.is_person & p['last'].notna() & p['first'].notna()].copy()
    p['nk'] = p['last'].map(lastkey) + '|' + p['first'].map(canon_first)
    g = p.groupby(['nk', 'contractor_key']).agg(first=('first', 'first'), last=('last', 'first'), contractor=('contractor', 'first'),
                                                roles=('party_type', lambda s: ', '.join(sorted(set(s.dropna())))),
                                                first_seen=('date_signed', 'min'), last_seen=('date_signed', 'max'),
                                                n_filings=('filing_key', 'nunique')).reset_index()
    g['role_id'] = 'P:' + g.nk + '|' + g.contractor_key
    g['kind'] = 'principal'
    g['org_key'] = g.contractor_key
    g['org'] = g.contractor
    return g


def lobbyists():
    lc = pd.read_parquet(os.path.join(INT, 'lobby_contacts.parquet'))
    lp = pd.read_parquet(os.path.join(INT, 'lobby_payments.parquet'))
    d = pd.read_parquet(os.path.join(INT, 'lob_directory.parquet'))
    rows = pd.concat([lc[['lobbyistname', 'firmname', 'date']], lp[['lobbyistname', 'firmname', 'date']]])
    rows = pd.concat([rows, d.rename(columns={'initialregistrationdate': 'date'})[['lobbyistname', 'firmname', 'date']]])
    rows['date'] = pd.to_datetime(rows.date.astype(str).str[:10], errors='coerce')
    rows = rows[rows.lobbyistname.notna() & rows.lobbyistname.str.contains(',')]
    rows['last'] = rows.lobbyistname.str.split(',').str[0]
    rows['first'] = rows.lobbyistname.str.split(',').str[1].str.strip()
    rows['nk'] = rows['last'].map(lastkey) + '|' + rows['first'].map(canon_first)
    g = rows.groupby('nk').agg(first=('first', 'first'), last=('last', 'first'), org=('firmname', lambda s: ' | '.join(s.dropna().value_counts().index[:3])),
                               first_seen=('date', 'min'), last_seen=('date', 'max'), lobbyistname=('lobbyistname', 'first')).reset_index()
    g['role_id'] = 'L:' + g.nk
    g['kind'] = 'lobbyist'
    g['roles'] = 'registered lobbyist'
    g['org_key'] = g.org.fillna('').map(lambda s: org_key(s.split(' | ')[0]) if s else '')
    return g


def main():
    elem, prof = donor_profiles()
    name_count = prof.groupby('nk').size()
    people = pd.concat([principals(), lobbyists()], ignore_index=True)
    cand = people.merge(prof, on='nk', suffixes=('', '_d'))
    print('candidate person-donor pairs', len(cand), 'people', cand.role_id.nunique())
    cand['name_profiles'] = cand.nk.map(name_count)
    cand['emp_sim'] = [emp_sim(e, k) for e, k in zip(cand.employers, cand.org_key)]
    # lobbyists: also compare to generic lobbying occupations
    cand['occ_exec'] = cand.occupations.fillna('').str.upper().str.contains(EXEC)
    cand['occ_lobby'] = cand.occupations.fillna('').str.upper().str.contains(r'LOBBY|GOVERNMENT RELATIONS|PUBLIC AFFAIRS|CONSULT|ATTORNEY|LAWYER')
    dec, conf, why = [], [], []
    for r in cand.itertuples():
        if r.emp_sim >= 92:
            dec.append('same'); conf.append(0.95 if r.name_profiles <= 3 else 0.9); why.append(f'donor employer matches {r.kind} organization (similarity {r.emp_sim:.0f})')
        elif r.kind == 'lobbyist' and r.occ_lobby and r.name_profiles <= 2 and r.emp_sim >= 60:
            dec.append('same'); conf.append(0.85); why.append('lobbying-related occupation, related employer, rare name')
        elif r.name_profiles > 10:
            dec.append('unsure'); conf.append(0.3); why.append('very common name without employer corroboration')
        else:
            dec.append('llm'); conf.append(None); why.append('')
    cand['decision'] = dec; cand['confidence'] = conf; cand['rationale'] = why
    cand['decided_by'] = np.where(cand.decision == 'llm', '', 'rule')
    todo = cand[cand.decision == 'llm'].copy().reset_index(drop=True)
    todo['cand_id'] = todo.index

    def pdesc(r):
        s = f"{r['first']} {r['last']}; {r['roles']} of {r['org']}" if r['kind'] == 'principal' else f"{r['first']} {r['last']}; registered SF lobbyist, firm(s): {r['org'] or 'n/a'}"
        fs = r['first_seen']; ls = r['last_seen']
        s += f"; listed {str(fs)[:10]} to {str(ls)[:10]}"
        return s

    def ddesc(r):
        return (f"name(s): {r['first_d']} {r['last_d']}; city: {r['city']}, {r['state']} {r['zip5']}; employer(s): {r['employers'] or 'none given'}; "
                f"occupation(s): {r['occupations'] or 'none given'}; {int(r['n'])} contributions ${r['total']:,.0f} from {str(r['first_date'])[:10]} to {str(r['last_date'])[:10]}")
    recs = []
    for r in todo.to_dict('records'):
        recs.append({'cand_id': r['cand_id'], 'person_desc': pdesc(r), 'donor_desc': ddesc(r), 'name_profiles': int(r['name_profiles'])})
    batches = [recs[i:i + 20] for i in range(0, len(recs), 20)]
    print('LLM candidates', len(recs), 'batches', len(batches))
    out = []
    with cf.ThreadPoolExecutor(8) as ex:
        futs = [ex.submit(judge, b) for b in batches]
        for i, f in enumerate(cf.as_completed(futs)):
            try:
                out.extend(f.result())
            except Exception as e:
                print('err', repr(e)[:200])
            if i % 50 == 0:
                print(i, f'${llm.spent():.2f}', flush=True)
    j = pd.DataFrame(out).drop_duplicates('cand_id')
    j['decided_by'] = llm.SONNET
    m = todo.drop(columns=['decision', 'confidence', 'rationale', 'decided_by']).merge(j, on='cand_id', how='left')
    hard = m[(m.decision == 'unsure') & (m.name_profiles <= 3)]
    hrecs = [x for x in recs if x['cand_id'] in set(hard.cand_id)]
    hb = [hrecs[i:i + 10] for i in range(0, len(hrecs), 10)]
    print('opus escalations', len(hrecs))
    out2 = []
    with cf.ThreadPoolExecutor(4) as ex:
        for f in cf.as_completed([ex.submit(judge, b, llm.OPUS, 'high', 'person_match_opus') for b in hb]):
            try:
                out2.extend(f.result())
            except Exception as e:
                print('err', repr(e)[:200])
    if out2:
        j2 = pd.DataFrame(out2).drop_duplicates('cand_id'); j2['decided_by'] = llm.OPUS
        m = m.drop(columns=['decision', 'confidence', 'rationale', 'decided_by']).merge(
            pd.concat([j[~j.cand_id.isin(j2.cand_id)], j2]), on='cand_id', how='left')
    res = pd.concat([cand[cand.decision != 'llm'], m.drop(columns=['cand_id'])], ignore_index=True)
    res.to_parquet(os.path.join(ER, 'person_matches.parquet'), index=False)
    elem.to_parquet(os.path.join(ER, 'donor_elements.parquet'), index=False)
    prof.to_parquet(os.path.join(ER, 'donor_profiles.parquet'), index=False)
    print(res.groupby(['kind', 'decision']).size()); print(f'spent ${llm.spent():.2f}')


if __name__ == '__main__':
    main()
